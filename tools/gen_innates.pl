#!/usr/bin/perl
# Generates lib/b24_subclass_innates.tpa and the strings @2000 on in tra/english/setup.tra from
# tools/subclass_innates.txt. Run from the mod root: perl tools/gen_innates.pl
use strict;
use warnings;

# The strings start well above the hand-written ones (@1 to @999) so the list can grow.
my $first = 2000;
my (@laf, @tra);
my $ref = $first;

open my $spec, '<', 'tools/subclass_innates.txt' or die "tools/subclass_innates.txt: $!";
while (my $line = <$spec>) {
	chomp $line;
	$line =~ s/\r$//;
	next if $line =~ /^\s*(#|$)/;
	my ($res, $icon, $range, $name, $desc) = split /\|/, $line, 5;
	die "bad line: $line\n" unless defined $desc;
	$desc =~ s/\\n/\n/g; # line breaks in the description
	my $target = '';
	if ($range == 1) { $target = ' touch = 1' }
	elsif ($range > 1) { $target = " touch = 1 range = $range" }
	push @laf, sprintf("LAF b24_create_innate INT_VAR name = RESOLVE_STR_REF (\@%d) description = RESOLVE_STR_REF (\@%d) opcode = 402%s\n  STR_VAR resref = ~%s~ icon = ~%s~ effect_res = ~%s~ END\n",
		$ref, $ref + 1, $target, $res, $icon, $res);
	push @tra, "\@$ref = ~$name~\n", sprintf("\@%d = ~%s~\n", $ref + 1, $desc);
	$ref += 2;
}
close $spec;

open my $out, '>', 'lib/b24_subclass_innates.tpa' or die;
print $out "// Generated by tools/gen_innates.pl from tools/subclass_innates.txt; do not edit by hand.\n";
print $out "// Innate abilities of the subclasses beyond the SRD (lua/B24X*.lua) and Font of Magic.\n\n";
print $out @laf;
close $out;

# Replace the generated block in the tra file.
my $traFile = 'tra/english/setup.tra';
open my $in, '<', $traFile or die;
my $text = do { local $/; <$in> };
close $in;
# Git may check the file out with CRLF line endings; the block markers below use LF.
$text =~ s/\r\n/\n/g;
my $begin = "// Subclass innates (generated by tools/gen_innates.pl)\n";
my $end = "// End of subclass innates\n";
$text =~ s/\Q$begin\E.*?\Q$end\E//gs;
$text .= "\n" unless $text =~ /\n$/;
$text .= $begin . join('', @tra) . $end;
open my $tout, '>', $traFile or die;
print $tout $text;
close $tout;
printf "%d innates, strings \@%d-\@%d\n", scalar(@laf), $first, $ref - 1;
